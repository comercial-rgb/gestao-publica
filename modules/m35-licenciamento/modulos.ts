/**
 * M35 — O CATÁLOGO COMERCIAL: quais MÓDULOS existem para contratar, e a que módulo cada
 * ação do sistema pertence (V10 T1 · N6.1).
 *
 * ═══ ⚠️ ISTO NÃO É UM SEGUNDO CENSO DE PERMISSÕES ═══
 * Permissão responde "este usuário pode?". Habilitação responde "este município
 * CONTRATOU?". São perguntas diferentes, com donos diferentes — a permissão é do
 * administrador do ente, a habilitação é do fornecedor — e por isso NÃO se misturam numa
 * tabela só. Um servidor com a ação `EMPENHAR` num ente que não contratou o núcleo contábil
 * continua sem empenhar, e o motivo que ele lê é o certo.
 *
 * ═══ ⚠️ O `Record` EXAUSTIVO É A REDE, e ela já provou o valor no `AREA_DA_ACAO` ═══
 * `MODULO_DA_ACAO` é `Record<AcaoDoSistema, ModuloComercial>`. Uma ação nova no censo do
 * M16 NÃO COMPILA até alguém dizer a que módulo comercial ela pertence. Uma lista por
 * módulo ("o núcleo tem estas ações") aceitaria em silêncio a ação nova — e o efeito seria
 * uma funcionalidade entregue de graça, ou pior, uma funcionalidade que o gate solta porque
 * ninguém a classificou.
 *
 * ═══ ⚠️ `PLATAFORMA` NÃO É UM MÓDULO À VENDA — E NÃO É UMA GAVETA DE SOBRA ═══
 * Administração de usuários e perfis, cadastro canônico de Pessoa, suporte, anexos e
 * assinatura são a PLATAFORMA: existem em toda implantação, em qualquer contrato, e nunca
 * são suspensos. Se fossem licenciáveis, suspender o contrato tiraria do município a
 * capacidade de administrar os próprios usuários e de ler a própria auditoria — e aí a
 * suspensão comercial viraria sequestro de dados.
 */

export type ModuloComercial =
  | "NUCLEO_CONTABIL"
  | "TRIBUTOS_E_ARRECADACAO"
  | "PATRIMONIO_E_ALMOXARIFADO"
  | "COMPRAS_E_CONTRATOS"
  | "PESSOAL_E_FOLHA"
  | "ATENDIMENTO_AO_CIDADAO"
  | "TRANSPARENCIA_E_CONTROLE"
  | "INTEGRACOES_E_PRESTACAO_DE_CONTAS"
  | "PLATAFORMA";

export interface ModuloDoCatalogo {
  readonly id: ModuloComercial;
  /** O nome comercial, em linguagem do ente — nunca "M05" nem "núcleo". */
  readonly nome: string;
  readonly descricao: string;
  /**
   * Os módulos SEM OS QUAIS este não funciona. Habilitar um módulo cuja dependência não
   * está contratada é RECUSADO nomeando a dependência — nunca habilitando-a por tabela.
   */
  readonly depende: readonly ModuloComercial[];
  /** `false` só para a PLATAFORMA: ela não se contrata, não se suspende, não se vende. */
  readonly licenciavel: boolean;
}

