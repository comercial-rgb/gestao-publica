/** Os módulos que SE CONTRATAM — a PLATAFORMA fica de fora, e é o único caso. */
export const MODULOS_LICENCIAVEIS: readonly ModuloComercial[] = CATALOGO_DE_MODULOS.filter(
  (m) => m.licenciavel
).map((m) => m.id);

export function moduloDoCatalogo(id: ModuloComercial): ModuloDoCatalogo {
  const achado = CATALOGO_DE_MODULOS.find((m) => m.id === id);
  if (achado === undefined) {
    throw new Error(`MÓDULO COMERCIAL DESCONHECIDO: "${id}". Nada foi gravado.`);
  }
  return achado;
}

/** O nome comercial, para a mensagem que o servidor público lê. */
export function nomeDoModulo(id: ModuloComercial): string {
  return moduloDoCatalogo(id).nome;
}

